#!/usr/bin/env bash
# ══════════════════════════════════════════════════════════════════════════════
#  Alchemy Trading Platform — One-Click Deploy
# ══════════════════════════════════════════════════════════════════════════════
#
#  Usage (on a fresh Ubuntu 22/24 VPS):
#    curl -sSL https://raw.githubusercontent.com/jaikumararjunan/alchemy/main/deploy.sh | bash
#
#  Or locally:
#    cd /opt/alchemy && bash deploy.sh
#
#  What this does:
#    1. Installs Docker + Docker Compose (if missing)
#    2. Clones/updates repo to /opt/alchemy
#    3. Generates .env with secure random secrets (if missing)
#    4. Builds and starts all services
#    5. Sets up UFW firewall + Fail2ban
#    6. Verifies health check
# ══════════════════════════════════════════════════════════════════════════════
set -euo pipefail

INSTALL_DIR="/opt/alchemy"
REPO_URL="https://github.com/jaikumararjunan/alchemy.git"
BRANCH="main"

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
NC='\033[0m'

log()  { echo -e "${CYAN}[ALCHEMY]${NC} $1"; }
ok()   { echo -e "${GREEN}[  OK  ]${NC} $1"; }
warn() { echo -e "${YELLOW}[ WARN ]${NC} $1"; }
err()  { echo -e "${RED}[ERROR]${NC} $1"; }

# ── 1. System Dependencies ───────────────────────────────────────────────────
install_docker() {
    if command -v docker &>/dev/null; then
        ok "Docker already installed: $(docker --version)"
        return
    fi
    log "Installing Docker..."
    curl -fsSL https://get.docker.com | sh
    systemctl enable docker && systemctl start docker
    ok "Docker installed"
}

install_deps() {
    log "Installing system packages..."
    apt-get update -qq
    apt-get install -y -qq git curl ufw fail2ban jq > /dev/null 2>&1
    ok "System packages installed"
}

# ── 2. Clone / Update Repo ───────────────────────────────────────────────────
setup_repo() {
    if [ -d "$INSTALL_DIR/.git" ]; then
        log "Updating existing repo..."
        cd "$INSTALL_DIR"
        git fetch origin "$BRANCH" --quiet
        git reset --hard "origin/$BRANCH" --quiet
        ok "Repo updated to latest $BRANCH"
    else
        log "Cloning repository..."
        git clone --depth 1 -b "$BRANCH" "$REPO_URL" "$INSTALL_DIR"
        ok "Repo cloned to $INSTALL_DIR"
    fi
    cd "$INSTALL_DIR"
}

# ── 3. Generate .env ─────────────────────────────────────────────────────────
generate_env() {
    if [ -f "$INSTALL_DIR/.env" ]; then
        ok ".env already exists — skipping generation"
        return
    fi

    log "Generating .env with secure secrets..."

    JWT_SECRET=$(openssl rand -base64 48 | tr -dc 'A-Za-z0-9!@#' | head -c 48)
    VAULT_KEY=$(openssl rand -base64 48 | tr -dc 'A-Za-z0-9!@#' | head -c 48)
    ADMIN_PWD="Alchemy#$(openssl rand -hex 4)!"

    cat > "$INSTALL_DIR/.env" << ENVEOF
# ── Alchemy Production Environment ──────────────────────────
# Generated by deploy.sh on $(date -u +"%Y-%m-%d %H:%M:%S UTC")
ENV=production
LOG_LEVEL=info
ENABLE_AI_AGENTS=false

# Security (auto-generated — change if desired)
JWT_SECRET_KEY=${JWT_SECRET}
ALCHEMY_VAULT_KEY=${VAULT_KEY}

# Database (SQLite for quick start; switch to PostgreSQL for production scale)
DATABASE_URL=sqlite+aiosqlite:////data/alchemy.db

# Admin account
ADMIN_EMAIL=admin@alchemy.in
ADMIN_PASSWORD=${ADMIN_PWD}

# Domain (update to your actual domain)
DOMAIN=localhost

# Email OTP (configure for password reset / 2FA)
# SMTP_HOST=smtp.gmail.com
# SMTP_PORT=587
# SMTP_USER=your@gmail.com
# SMTP_PASSWORD=your-app-password
# SMTP_FROM=your@gmail.com

# Grafana
GRAFANA_USER=admin
GRAFANA_PASSWORD=alchemy2026
ENVEOF

    chmod 600 "$INSTALL_DIR/.env"
    ok ".env generated"
    echo ""
    echo -e "  ${YELLOW}═══════════════════════════════════════════════${NC}"
    echo -e "  ${YELLOW}  SAVE THESE CREDENTIALS:${NC}"
    echo -e "  ${YELLOW}  Admin email:    admin@alchemy.in${NC}"
    echo -e "  ${YELLOW}  Admin password: ${ADMIN_PWD}${NC}"
    echo -e "  ${YELLOW}  Grafana:        admin / alchemy2026${NC}"
    echo -e "  ${YELLOW}═══════════════════════════════════════════════${NC}"
    echo ""
}

# ── 4. Build & Start ─────────────────────────────────────────────────────────
build_and_start() {
    cd "$INSTALL_DIR"

    # Stop any existing containers
    log "Stopping existing containers..."
    docker compose -f docker-compose.prod.yml down --remove-orphans 2>/dev/null || true

    # Build
    log "Building Alchemy Docker image (this may take 3-5 minutes)..."
    docker compose -f docker-compose.prod.yml build --quiet

    # Start
    log "Starting all services..."
    docker compose -f docker-compose.prod.yml up -d

    ok "All services started"
}

# ── 5. Firewall ──────────────────────────────────────────────────────────────
setup_firewall() {
    log "Configuring UFW firewall..."
    ufw --force reset > /dev/null 2>&1
    ufw default deny incoming > /dev/null 2>&1
    ufw default allow outgoing > /dev/null 2>&1
    ufw allow 22/tcp > /dev/null 2>&1
    ufw allow 80/tcp > /dev/null 2>&1
    ufw allow 443/tcp > /dev/null 2>&1
    ufw --force enable > /dev/null 2>&1
    ok "Firewall enabled (22, 80, 443 only)"

    # Fail2ban
    systemctl enable fail2ban > /dev/null 2>&1
    systemctl restart fail2ban > /dev/null 2>&1
    ok "Fail2ban enabled"
}

# ── 6. Health Check ──────────────────────────────────────────────────────────
wait_for_health() {
    log "Waiting for Alchemy to start..."
    local retries=30
    local i=0
    while [ $i -lt $retries ]; do
        if curl -sf http://localhost:8000/health > /dev/null 2>&1; then
            ok "Alchemy is running!"
            echo ""
            HEALTH=$(curl -s http://localhost:8000/health)
            echo -e "  ${GREEN}Health: ${HEALTH}${NC}"
            return 0
        fi
        sleep 2
        i=$((i + 1))
        echo -n "."
    done
    echo ""
    warn "Health check timed out. Check logs: docker compose -f docker-compose.prod.yml logs alchemy"
    return 1
}

# ── 7. Print Summary ─────────────────────────────────────────────────────────
print_summary() {
    local IP=$(curl -s ifconfig.me 2>/dev/null || echo "your-server-ip")
    echo ""
    echo -e "${GREEN}══════════════════════════════════════════════════════════${NC}"
    echo -e "${GREEN}  ALCHEMY DEPLOYED SUCCESSFULLY!${NC}"
    echo -e "${GREEN}══════════════════════════════════════════════════════════${NC}"
    echo ""
    echo -e "  Dashboard:   ${CYAN}http://${IP}${NC}"
    echo -e "  API Health:  ${CYAN}http://${IP}/api/health${NC}"
    echo -e "  Swagger:     ${CYAN}http://${IP}/docs${NC}"
    echo ""
    echo -e "  ${YELLOW}Next steps:${NC}"
    echo -e "    1. Update DOMAIN in /opt/alchemy/.env"
    echo -e "    2. Set up SSL: certbot certonly --webroot -w /var/www/certbot -d yourdomain.com"
    echo -e "    3. Configure Telegram notifications in the dashboard"
    echo -e "    4. Change the admin password on first login"
    echo ""
    echo -e "  ${YELLOW}Useful commands:${NC}"
    echo -e "    Logs:     docker compose -f /opt/alchemy/docker-compose.prod.yml logs -f alchemy"
    echo -e "    Restart:  docker compose -f /opt/alchemy/docker-compose.prod.yml restart"
    echo -e "    Stop:     docker compose -f /opt/alchemy/docker-compose.prod.yml down"
    echo -e "    Update:   cd /opt/alchemy && git pull && bash deploy.sh"
    echo ""
}

# ══════════════════════════════════════════════════════════════════════════════
#  MAIN
# ══════════════════════════════════════════════════════════════════════════════
main() {
    echo ""
    echo -e "${CYAN}══════════════════════════════════════════════════════════${NC}"
    echo -e "${CYAN}  ALCHEMY TRADING PLATFORM — ONE-CLICK DEPLOY${NC}"
    echo -e "${CYAN}══════════════════════════════════════════════════════════${NC}"
    echo ""

    # Check root
    if [ "$(id -u)" -ne 0 ]; then
        err "Please run as root: sudo bash deploy.sh"
        exit 1
    fi

    install_deps
    install_docker
    setup_repo
    generate_env
    build_and_start
    setup_firewall
    wait_for_health
    print_summary
}

main "$@"
