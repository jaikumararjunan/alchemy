#!/usr/bin/env bash
# =============================================================================
# Alchemy — Emergency Rollback Script
# =============================================================================
#
# Usage:
#   bash rollback.sh [auto|manual] [triggering_sha]
#
# Modes:
#   auto    — triggered automatically by deploy.sh on health check failure
#   manual  — invoked by operator or via GitHub Actions workflow_dispatch
#
# What it does:
#  1. Reads the currently active slot from .active_slot.
#  2. Determines the INACTIVE slot (which holds the previously working version).
#  3. Starts the inactive slot if not already running.
#  4. Waits for its health check.
#  5. Switches nginx upstream back to the inactive (old) slot.
#  6. Updates .active_slot.
#  7. Writes rollback audit record.
# =============================================================================
set -euo pipefail

MODE="${1:-manual}"
TRIGGER_SHA="${2:-unknown}"

APP_DIR="/opt/alchemy"
SLOT_FILE="${APP_DIR}/.active_slot"
PREV_TAG_FILE="${APP_DIR}/.previous_tag"
UPSTREAM_CONF="${APP_DIR}/upstream.conf"
ROLLBACK_LOG="${APP_DIR}/logs/rollback.log"
COMPOSE_PROD="${APP_DIR}/docker-compose.prod.yml"

RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'
CYAN='\033[0;36m'; NC='\033[0m'

log()  { echo -e "$(date -u +%H:%M:%S) ${CYAN}[rollback]${NC} $*" | tee -a "$ROLLBACK_LOG"; }
ok()   { echo -e "$(date -u +%H:%M:%S) ${GREEN}[✓]${NC} $*"       | tee -a "$ROLLBACK_LOG"; }
warn() { echo -e "$(date -u +%H:%M:%S) ${YELLOW}[!]${NC} $*"      | tee -a "$ROLLBACK_LOG"; }
fail() { echo -e "$(date -u +%H:%M:%S) ${RED}[✗]${NC} $*"         | tee -a "$ROLLBACK_LOG"; exit 1; }

mkdir -p "${APP_DIR}/logs"
echo "" >> "$ROLLBACK_LOG"
log "════════════════════════════════════════════════════════"
log "ROLLBACK triggered | mode=${MODE} | sha=${TRIGGER_SHA}"
log "════════════════════════════════════════════════════════"

# ── Determine slots ───────────────────────────────────────────────────────────
FAILED_SLOT="$(cat "$SLOT_FILE" 2>/dev/null || echo 'green')"
if [[ "$FAILED_SLOT" == "blue" ]]; then
  ROLLBACK_SLOT="green"
else
  ROLLBACK_SLOT="blue"
fi
ROLLBACK_CONTAINER="alchemy-${ROLLBACK_SLOT}"
FAILED_CONTAINER="alchemy-${FAILED_SLOT}"

log "Failing slot    : ${FAILED_SLOT}  (${FAILED_CONTAINER})"
log "Rolling back to : ${ROLLBACK_SLOT} (${ROLLBACK_CONTAINER})"

# ── Show previous image for reference ────────────────────────────────────────
PREV_TAG="$(cat "$PREV_TAG_FILE" 2>/dev/null || echo 'unknown')"
log "Previous image: ${PREV_TAG}"

# ── Start rollback container if not running ───────────────────────────────────
ROLLBACK_STATUS=$(docker inspect --format '{{.State.Status}}' "$ROLLBACK_CONTAINER" 2>/dev/null || echo 'missing')
log "Rollback container status: ${ROLLBACK_STATUS}"

if [[ "$ROLLBACK_STATUS" != "running" ]]; then
  log "Starting rollback container ${ROLLBACK_CONTAINER}..."
  OVERRIDE_FILE="${APP_DIR}/docker-compose.${ROLLBACK_SLOT}.yml"
  docker compose -f "$COMPOSE_PROD" -f "$OVERRIDE_FILE" \
    --project-name "alchemy-${ROLLBACK_SLOT}" \
    up -d --no-recreate alchemy \
    || fail "Failed to start rollback container ${ROLLBACK_CONTAINER}"
fi

# ── Wait for rollback container to be healthy ─────────────────────────────────
log "Waiting for ${ROLLBACK_CONTAINER} health check (max 60s)..."
for ((i=1; i<=12; i++)); do
  STATUS=$(docker inspect --format '{{.State.Health.Status}}' "$ROLLBACK_CONTAINER" 2>/dev/null || echo 'starting')
  if [[ "$STATUS" == "healthy" ]]; then
    ok "${ROLLBACK_CONTAINER} is healthy"
    break
  fi
  log "  Health: ${STATUS} (${i}/12)..."
  sleep 5
  if [[ "$i" -eq 12 ]]; then
    warn "Rollback container not healthy after 60s — switching nginx anyway (best effort)"
  fi
done

# ── Switch nginx upstream ─────────────────────────────────────────────────────
log "Switching nginx upstream to ${ROLLBACK_SLOT}..."
cat > "$UPSTREAM_CONF" << NGINX_EOF
# Auto-generated by rollback.sh — do not edit manually
# Rollback to slot: ${ROLLBACK_SLOT} | Time: $(date -u +%Y-%m-%dT%H:%M:%SZ)
server ${ROLLBACK_CONTAINER}:8000;
NGINX_EOF

docker exec nginx nginx -s reload 2>/dev/null || \
  docker compose -f "$COMPOSE_PROD" exec -T nginx nginx -s reload 2>/dev/null || \
  warn "nginx reload failed — upstream file updated but reload may need manual trigger"

ok "nginx upstream switched to ${ROLLBACK_SLOT}"

# ── Verify rollback is live ───────────────────────────────────────────────────
sleep 8
HTTP_CODE=$(curl -s -o /dev/null -w '%{http_code}' \
  --max-time 8 http://localhost:8000/health 2>/dev/null || echo "000")
if [[ "$HTTP_CODE" =~ ^2 ]]; then
  ok "Rollback health check passed (HTTP ${HTTP_CODE})"
else
  warn "Health check returned HTTP ${HTTP_CODE} after rollback — investigate manually"
fi

# ── Update active slot ────────────────────────────────────────────────────────
echo "$ROLLBACK_SLOT" > "$SLOT_FILE"
ok "Active slot set to: ${ROLLBACK_SLOT}"

# ── Stop failed container ─────────────────────────────────────────────────────
log "Stopping failed container ${FAILED_CONTAINER}..."
docker stop "$FAILED_CONTAINER" 2>/dev/null || warn "${FAILED_CONTAINER} already stopped"

# ── Audit log ─────────────────────────────────────────────────────────────────
printf '%s\n' \
  "$(date -u +%Y-%m-%dT%H:%M:%SZ) | rollback | mode=${MODE} | failed_slot=${FAILED_SLOT} | rollback_slot=${ROLLBACK_SLOT} | prev_tag=${PREV_TAG} | trigger_sha=${TRIGGER_SHA}" \
  >> "${APP_DIR}/logs/deploy-audit.log"

log "════════════════════════════════════════════════════════"
ok "Rollback complete — serving from ${ROLLBACK_SLOT} (${ROLLBACK_CONTAINER})"
log "════════════════════════════════════════════════════════"
