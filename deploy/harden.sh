#!/usr/bin/env bash
# =============================================================================
# Alchemy — Server Hardening Script
# =============================================================================
#
# Usage (run ONCE as root on a fresh Contabo VPS):
#   bash harden.sh [--skip-ssh] [--skip-ufw] [--skip-fail2ban] [--dry-run]
#
# What it does:
#   1.  Creates a dedicated non-root deploy user (alchemy) if not present
#   2.  Hardens SSH: key-only auth, no root login, strong ciphers
#   3.  Configures UFW firewall: allow 22/80/443 only
#   4.  Installs & configures fail2ban: SSH + nginx protection
#   5.  Applies sysctl security/performance parameters
#   6.  Enables auditd with rules for privileged command tracking
#   7.  Installs Docker (if not present) with secure daemon config
#   8.  Sets up /opt/alchemy directory with correct ownership/permissions
#   9.  Disables unnecessary services
#  10.  Configures automatic security updates (unattended-upgrades)
#  11.  Sets ulimits and cgroup limits for container processes
#  12.  Writes hardening audit record
#
# Idempotent: safe to run multiple times.
# =============================================================================
set -euo pipefail

# ── Flags ─────────────────────────────────────────────────────────────────────
SKIP_SSH=false; SKIP_UFW=false; SKIP_FAIL2BAN=false; DRY=false
for arg in "$@"; do
  case $arg in
    --skip-ssh)       SKIP_SSH=true ;;
    --skip-ufw)       SKIP_UFW=true ;;
    --skip-fail2ban)  SKIP_FAIL2BAN=true ;;
    --dry-run)        DRY=true ;;
  esac
done

RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'
CYAN='\033[0;36m'; NC='\033[0m'

log()  { echo -e "$(date -u +%H:%M:%S) ${CYAN}[harden]${NC}  $*"; }
ok()   { echo -e "$(date -u +%H:%M:%S) ${GREEN}[✓]${NC} $*"; }
warn() { echo -e "$(date -u +%H:%M:%S) ${YELLOW}[!]${NC} $*"; }
fail() { echo -e "$(date -u +%H:%M:%S) ${RED}[✗]${NC} $*"; exit 1; }
run()  { if $DRY; then echo "[DRY] $*"; else eval "$*"; fi; }

if [[ "$EUID" -ne 0 ]]; then
  fail "This script must be run as root (sudo bash harden.sh)"
fi

log "════════════════════════════════════════════════════════"
log "Alchemy server hardening — $(date -u +%Y-%m-%dT%H:%M:%SZ)"
log "Dry-run: ${DRY}"
log "════════════════════════════════════════════════════════"

# ── 1. Create alchemy system user ─────────────────────────────────────────────
log "Creating alchemy user..."
if ! id alchemy &>/dev/null; then
  run useradd --system --no-create-home --shell /sbin/nologin --comment "Alchemy trading bot" alchemy
  ok "User 'alchemy' created"
else
  ok "User 'alchemy' already exists"
fi

# Add alchemy to docker group so containers can be managed
if getent group docker &>/dev/null; then
  run usermod -aG docker alchemy 2>/dev/null || true
  ok "alchemy added to docker group"
fi

# ── 2. Set up /opt/alchemy directories ────────────────────────────────────────
log "Setting up /opt/alchemy directory structure..."
for dir in /opt/alchemy /opt/alchemy/logs /opt/alchemy/deploy /opt/alchemy/scripts; do
  run mkdir -p "$dir"
done
run chown -R alchemy:alchemy /opt/alchemy
run chmod 750 /opt/alchemy
run chmod 700 /opt/alchemy/logs
ok "Directory structure ready"

# ── 3. SSH hardening ──────────────────────────────────────────────────────────
if ! $SKIP_SSH; then
  log "Hardening SSH..."
  SSHD_CONF="/etc/ssh/sshd_config.d/99-alchemy-hardening.conf"
  run cat > "$SSHD_CONF" << 'SSHEOF'
# Alchemy server hardening — do not edit manually
# Generated by harden.sh

# Authentication
PermitRootLogin no
PasswordAuthentication no
PubkeyAuthentication yes
AuthenticationMethods publickey
PermitEmptyPasswords no
ChallengeResponseAuthentication no
KerberosAuthentication no
GSSAPIAuthentication no

# Session controls
LoginGraceTime 30
MaxAuthTries 3
MaxSessions 5
MaxStartups 5:50:10

# Disable unused features
X11Forwarding no
AllowAgentForwarding no
AllowTcpForwarding no
PermitTunnel no

# Strong algorithms only
KexAlgorithms curve25519-sha256,curve25519-sha256@libssh.org,ecdh-sha2-nistp521
Ciphers chacha20-poly1305@openssh.com,aes256-gcm@openssh.com,aes128-gcm@openssh.com
MACs hmac-sha2-512-etm@openssh.com,hmac-sha2-256-etm@openssh.com

# Logging
LogLevel VERBOSE
SyslogFacility AUTH

# Idle timeout: disconnect after 15 min idle
ClientAliveInterval 300
ClientAliveCountMax 3
SSHEOF
  run chmod 600 "$SSHD_CONF"
  run sshd -t && run systemctl reload sshd
  ok "SSH hardened (key-only, no root login, strong ciphers)"
else
  warn "SSH hardening skipped (--skip-ssh)"
fi

# ── 4. UFW firewall ───────────────────────────────────────────────────────────
if ! $SKIP_UFW; then
  log "Configuring UFW firewall..."
  if ! command -v ufw &>/dev/null; then
    run apt-get install -y ufw
  fi
  run ufw --force reset
  run ufw default deny incoming
  run ufw default allow outgoing
  run ufw allow 22/tcp comment "SSH"
  run ufw allow 80/tcp comment "HTTP (redirect to HTTPS)"
  run ufw allow 443/tcp comment "HTTPS"
  # Prometheus scraping from localhost only (Docker bridge) — no external access
  run ufw deny 9090/tcp comment "Prometheus — deny external"
  run ufw deny 3000/tcp comment "Grafana — deny external (use /grafana/ proxy)"
  run ufw --force enable
  ok "UFW firewall configured (22/80/443 only)"
else
  warn "UFW configuration skipped (--skip-ufw)"
fi

# ── 5. fail2ban ───────────────────────────────────────────────────────────────
if ! $SKIP_FAIL2BAN; then
  log "Installing/configuring fail2ban..."
  if ! command -v fail2ban-client &>/dev/null; then
    run apt-get install -y fail2ban
  fi

  run cat > /etc/fail2ban/jail.d/alchemy.conf << 'F2BEOF'
[DEFAULT]
bantime  = 3600
findtime = 600
maxretry = 5
backend  = systemd

[sshd]
enabled  = true
port     = ssh
logpath  = %(sshd_log)s
maxretry = 3
bantime  = 86400

[nginx-http-auth]
enabled  = true
filter   = nginx-http-auth
port     = http,https
logpath  = /var/log/nginx/alchemy_error.log

[nginx-req-limit]
enabled  = true
filter   = nginx-req-limit
port     = http,https
logpath  = /var/log/nginx/alchemy_error.log

[nginx-botsearch]
enabled  = true
filter   = nginx-botsearch
port     = http,https
logpath  = /var/log/nginx/alchemy_access.log
maxretry = 2
F2BEOF

  # nginx rate-limit filter (catches 429s from our rate limiting zones)
  run cat > /etc/fail2ban/filter.d/nginx-req-limit.conf << 'FILTEREOF'
[Definition]
failregex = ^<HOST>.*"(GET|POST|PUT|DELETE).*" 429
ignoreregex =
FILTEREOF

  run systemctl enable fail2ban
  run systemctl restart fail2ban
  ok "fail2ban configured (SSH + nginx protection)"
else
  warn "fail2ban configuration skipped (--skip-fail2ban)"
fi

# ── 6. sysctl security/performance parameters ─────────────────────────────────
log "Applying sysctl parameters..."
run cat > /etc/sysctl.d/99-alchemy.conf << 'SYSCTL'
# Network security
net.ipv4.tcp_syncookies = 1
net.ipv4.conf.all.rp_filter = 1
net.ipv4.conf.default.rp_filter = 1
net.ipv4.icmp_echo_ignore_broadcasts = 1
net.ipv4.icmp_ignore_bogus_error_responses = 1
net.ipv4.conf.all.log_martians = 1
net.ipv4.conf.default.log_martians = 1
net.ipv4.conf.all.accept_redirects = 0
net.ipv4.conf.default.accept_redirects = 0
net.ipv4.conf.all.accept_source_route = 0
net.ipv4.conf.default.accept_source_route = 0
net.ipv4.conf.all.send_redirects = 0
net.ipv4.conf.default.send_redirects = 0
net.ipv6.conf.all.accept_redirects = 0
net.ipv6.conf.default.accept_redirects = 0

# Kernel hardening
kernel.dmesg_restrict = 1
kernel.kptr_restrict = 2
kernel.randomize_va_space = 2
kernel.sysrq = 0
fs.protected_hardlinks = 1
fs.protected_symlinks = 1
fs.suid_dumpable = 0

# Performance (for high-frequency trading workload)
net.core.somaxconn = 65535
net.ipv4.tcp_max_syn_backlog = 65535
net.core.netdev_max_backlog = 5000
net.ipv4.tcp_fin_timeout = 15
net.ipv4.tcp_keepalive_time = 300
net.ipv4.tcp_keepalive_intvl = 30
net.ipv4.tcp_keepalive_probes = 5
vm.swappiness = 10
SYSCTL
run sysctl -p /etc/sysctl.d/99-alchemy.conf
ok "sysctl parameters applied"

# ── 7. auditd ─────────────────────────────────────────────────────────────────
log "Configuring auditd..."
if ! command -v auditctl &>/dev/null; then
  run apt-get install -y auditd
fi

run cat > /etc/audit/rules.d/99-alchemy.rules << 'AUDITEOF'
# Alchemy audit rules

# Delete all existing rules first
-D

# Buffer size
-b 8192

# Failures → log
-f 1

# Monitor privileged commands
-a always,exit -F arch=b64 -S execve -F euid=0 -k root_commands
-a always,exit -F arch=b64 -S execve -F uid=alchemy -k alchemy_commands

# Monitor /opt/alchemy writes (detect tampering)
-w /opt/alchemy/.env -p wa -k alchemy_secrets
-w /opt/alchemy/deploy/ -p wa -k alchemy_deploy
-w /opt/alchemy/.active_slot -p wa -k alchemy_slot

# Monitor Docker daemon socket access
-w /var/run/docker.sock -p rwxa -k docker_socket

# Monitor SSH config changes
-w /etc/ssh/sshd_config -p wa -k ssh_config
-w /etc/ssh/sshd_config.d/ -p wa -k ssh_config

# Monitor cron
-w /etc/cron.d/ -p wa -k cron
-w /etc/crontab -p wa -k cron

# Monitor sudo
-w /usr/bin/sudo -p x -k sudo_usage
-w /etc/sudoers -p wa -k sudoers

# Network changes
-a always,exit -F arch=b64 -S sethostname -S setdomainname -k network_changes
-w /etc/hosts -p wa -k hosts_file

# Immutable (must reboot to change rules)
-e 2
AUDITEOF

run systemctl enable auditd
run systemctl restart auditd
ok "auditd configured with Alchemy-specific rules"

# ── 8. Docker daemon hardening ────────────────────────────────────────────────
log "Hardening Docker daemon..."
run mkdir -p /etc/docker
run cat > /etc/docker/daemon.json << 'DOCKEREOF'
{
  "log-driver": "json-file",
  "log-opts": {
    "max-size": "50m",
    "max-file": "5"
  },
  "userland-proxy": false,
  "no-new-privileges": true,
  "icc": false,
  "live-restore": true,
  "default-ulimits": {
    "nofile": {
      "Name": "nofile",
      "Hard": 65536,
      "Soft": 65536
    }
  },
  "storage-driver": "overlay2"
}
DOCKEREOF
# Restart only if docker is running — avoid disrupting containers during harden
if systemctl is-active --quiet docker; then
  warn "Docker running — daemon config will apply on next restart"
  warn "Run: systemctl restart docker (schedule during maintenance window)"
else
  run systemctl enable docker
fi
ok "Docker daemon config written"

# ── 9. Disable unnecessary services ──────────────────────────────────────────
log "Disabling unnecessary services..."
DISABLE_SERVICES=(
  "avahi-daemon"
  "cups"
  "bluetooth"
  "ModemManager"
  "snapd"
)
for svc in "${DISABLE_SERVICES[@]}"; do
  if systemctl is-enabled --quiet "$svc" 2>/dev/null; then
    run systemctl disable --now "$svc" 2>/dev/null || true
    ok "Disabled: ${svc}"
  fi
done

# ── 10. Automatic security updates ────────────────────────────────────────────
log "Configuring automatic security updates..."
if ! dpkg -l unattended-upgrades &>/dev/null; then
  run apt-get install -y unattended-upgrades apt-listchanges
fi
run cat > /etc/apt/apt.conf.d/50unattended-upgrades << 'UPGEOF'
Unattended-Upgrade::Allowed-Origins {
    "${distro_id}:${distro_codename}-security";
    "${distro_id}ESMApps:${distro_codename}-apps-security";
    "${distro_id}ESM:${distro_codename}-infra-security";
};
Unattended-Upgrade::Package-Blacklist {};
Unattended-Upgrade::AutoFixInterruptedDpkg "true";
Unattended-Upgrade::MinimalSteps "true";
Unattended-Upgrade::Remove-Unused-Kernel-Packages "true";
Unattended-Upgrade::Remove-New-Unused-Dependencies "true";
Unattended-Upgrade::Automatic-Reboot "false";
Unattended-Upgrade::Mail "root";
UPGEOF

run cat > /etc/apt/apt.conf.d/20auto-upgrades << 'AUTOEOF'
APT::Periodic::Update-Package-Lists "1";
APT::Periodic::Unattended-Upgrade "1";
APT::Periodic::Download-Upgradeable-Packages "1";
APT::Periodic::AutocleanInterval "7";
AUTOEOF
ok "Automatic security updates configured"

# ── 11. Kernel module hardening ───────────────────────────────────────────────
log "Disabling unnecessary kernel modules..."
run cat > /etc/modprobe.d/alchemy-blacklist.conf << 'MODEOF'
# Disable rarely needed, potentially dangerous modules
install cramfs /bin/true
install freevxfs /bin/true
install hfs /bin/true
install hfsplus /bin/true
install jffs2 /bin/true
install udf /bin/true
install usb-storage /bin/true
install dccp /bin/true
install sctp /bin/true
install rds /bin/true
install tipc /bin/true
MODEOF
ok "Kernel module blacklist applied"

# ── 12. /tmp hardening ────────────────────────────────────────────────────────
log "Hardening /tmp..."
if ! mount | grep -q "on /tmp"; then
  run cat > /etc/systemd/system/tmp.mount << 'TMPMNT'
[Unit]
Description=Temporary Directory /tmp
ConditionPathIsSymbolicLink=!/tmp
DefaultDependencies=no
Conflicts=umount.target
Before=local-fs.target umount.target
After=swap.target

[Mount]
What=tmpfs
Where=/tmp
Type=tmpfs
Options=mode=1777,strictatime,nosuid,nodev,noexec,size=512M

[Install]
WantedBy=local-fs.target
TMPMNT
  run systemctl enable tmp.mount
  run systemctl start tmp.mount
  ok "/tmp mounted with nosuid,nodev,noexec"
else
  ok "/tmp already mounted (check options with: mount | grep /tmp)"
fi

# ── 13. Final audit record ────────────────────────────────────────────────────
AUDIT_FILE="/opt/alchemy/logs/harden-audit.log"
run mkdir -p "$(dirname "$AUDIT_FILE")"
if ! $DRY; then
  printf '%s | harden | skip_ssh=%s | skip_ufw=%s | skip_fail2ban=%s | host=%s\n' \
    "$(date -u +%Y-%m-%dT%H:%M:%SZ)" \
    "$SKIP_SSH" "$SKIP_UFW" "$SKIP_FAIL2BAN" \
    "$(hostname -f 2>/dev/null || hostname)" \
    >> "$AUDIT_FILE"
fi

log "════════════════════════════════════════════════════════"
ok "Server hardening complete"
log ""
log "Next steps:"
log "  1. Add your SSH public key to /home/<deploy-user>/.ssh/authorized_keys"
log "  2. Verify SSH login still works BEFORE closing this session"
log "  3. Restart Docker (schedule maintenance window): systemctl restart docker"
log "  4. Review auditd rules: auditctl -l"
log "  5. Check fail2ban status: fail2ban-client status"
log "  6. Check UFW status: ufw status verbose"
log "════════════════════════════════════════════════════════"
